'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
test('Windows launcher offers pinned verified FFmpeg setup only when the pair is missing', () => {
  const bat = fs.readFileSync(path.join(__dirname, '../ABRIR_DESENVOLVIMENTO.bat'), 'utf8')
  assert.match(bat, /GACHA_FFMPEG_PATH/)
  assert.match(bat, /GACHA_FFPROBE_PATH/)
  assert.match(bat, /if exist "resources\\video-tools\\ffmpeg.exe" if exist "resources\\video-tools\\ffprobe.exe"/)
  assert.match(bat, /choice \/c SN/)
  assert.match(bat, /prepare-ffmpeg-lgpl\.ps1/)
  assert.doesNotMatch(bat, /set "\\?PATH=/i)
})
test('verified media setup script rejects checksum mismatch and version alias', () => {
  const script = fs.readFileSync(path.join(__dirname, '../scripts/video-studio/prepare-ffmpeg-lgpl.ps1'), 'utf8')
  assert.match(script, /Get-FileHash -Algorithm SHA256/)
  assert.match(script, /releaseTag/)
  assert.match(script, /latest/)
  assert.match(script, /forbiddenConfigureFlags/)
})
