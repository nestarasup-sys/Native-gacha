'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const source=fs.readFileSync(path.join(__dirname,'../src/renderer/src/features/videoStudio/pixiGachaPoseSurface.ts'),'utf8')
test('real Pixi integration is lazily loaded and never owns a separate animation clock',()=>{
  assert.match(source,/await import\('pixi\.js'\)/)
  assert.match(source,/preferWebGLVersion: 2/)
  assert.match(source,/autoStart: false/)
  assert.match(source,/this\.rig\.setInterpolatedPose\(from, to, progress\)/)
  assert.doesNotMatch(source,/requestAnimationFrame\(/)
})
test('GPU surface guards draw until all real textures are loaded and abandons lost context',()=>{
  assert.match(source,/await this\.pixi\.Assets\.load\(url\)/)
  assert.match(source,/if \(!this\.loaded\.has\(part\.dataUrl\)\)/)
  assert.match(source,/webglcontextlost/)
  assert.match(source,/this\.rig\.dispose\(\)/)
  assert.match(source,/this\.app\.destroy\(true, \{ children: true \}\)/)
})
test('GPU renderer remains experimental, default Video Studio uses exact Canvas parity path',()=>{
  const editor=fs.readFileSync(path.join(__dirname,'../src/renderer/src/features/videoStudio/VideoStudioEditor.tsx'),'utf8')
  assert.doesNotMatch(editor,/PixiGachaPoseSurface|pixiGachaPoseSurface/)
  const transition=fs.readFileSync(path.join(__dirname,'../src/renderer/src/features/videoStudio/transitionRenderer.ts'),'utf8')
  assert.match(transition,/prepareSavedCharacterRenderer\(/)
  assert.match(transition,/renderToCanvas\(appearance, transforms, effects, mode\)/)
})
