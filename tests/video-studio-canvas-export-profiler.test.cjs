'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const ts=require('typescript')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')

test('export separates actual character Canvas cost from imported media and compositing',()=>{
 const surface=read('src/renderer/src/features/videoStudio/VideoExportSurfacePage.tsx')
 assert.match(surface,/let characterMs = 0, mediaDecodeMs = 0/)
 assert.match(surface,/characterMs = performance\.now\(\) - started/)
 assert.match(surface,/mediaDecodeMs = performance\.now\(\) - started/)
 assert.match(surface,/Promise\.allSettled\(/,'video decode and Gacha character work remain concurrent')
 assert.match(surface,/characterRenderer!\.renderFrame\(scene, true\)/)
 assert.match(surface,/timings: \{ composeMs, readbackMs, characterMs, mediaDecodeMs \}/)
 assert.match(surface,/context\.getImageData\(0, 0, VIDEO_STAGE_WIDTH, VIDEO_STAGE_HEIGHT\)/,
 'exact RGBA stage readback is unchanged for FFmpeg and byte parity')
})
test('IPC validates per-step performance values and retains original export frame contract',()=>{
 const shared=read('src/shared/videoExportSurface.ts')
 const host=read('electron/videoExportSurfaceHost.ts')
 assert.match(shared,/characterMs\?: number; mediaDecodeMs\?: number/)
 assert.match(host,/Number\.isFinite\(characterMs\) && characterMs >= 0 \? characterMs : 0/)
 assert.match(host,/Number\.isFinite\(mediaDecodeMs\) && mediaDecodeMs >= 0 \? mediaDecodeMs : 0/)
 assert.match(host,/Buffer\.from\(ready\.pixels\.buffer, ready\.pixels\.byteOffset, ready\.pixels\.byteLength\)/)
 assert.match(host,/pending\.frame !== ready\.frame/)
 const tsSource=ts.createSourceFile('videoExportSurfaceHost.ts',host,ts.ScriptTarget.ES2022,true)
 assert.equal(tsSource.parseDiagnostics.length,0)
})
test('export final job diagnostics show character cost, media decode and existing FFmpeg times',()=>{
 const coordinator=read('electron/videoExportCoordinator.ts')
 const metrics=read('src/shared/videoExportRuntime.ts')
 assert.match(metrics,/characterMs\?: number/)
 assert.match(metrics,/mediaDecodeMs\?: number/)
 assert.match(metrics,/composeMs\?: number/)
 assert.match(metrics,/writerWaitMs\?: number/)
 assert.match(coordinator,/characterMs \+= timings\.characterMs/)
 assert.match(coordinator,/mediaDecodeMs \+= timings\.mediaDecodeMs/)
 assert.equal(coordinator.split('        characterMs,\n        mediaDecodeMs,').length,4,
   'export rendering, assembly and final report must retain the new diagnostics')
 assert.match(coordinator,/surfaceOtherMs \+= Math\.max\(0, roundTripMs - timings\.composeMs - timings\.readbackMs\)/)
 assert.match(coordinator,/workerCount,/)
})
