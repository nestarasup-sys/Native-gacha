'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { resolve } = require('node:path')
const panel = readFileSync(resolve(__dirname, '../../src/renderer/src/features/editorV6/EditorV6ExportPanel.tsx'), 'utf8')
const controller = readFileSync(resolve(__dirname, '../../src/renderer/src/features/editorV6/useEditorV6ExportPanelController.ts'), 'utf8')
const profile = readFileSync(resolve(__dirname, '../../src/shared/editorV6Export.ts'), 'utf8')
const css = readFileSync(resolve(__dirname, '../../src/renderer/src/ui/styles.css'), 'utf8')
test('Editor V6 exposes standard MP4 actions with and without experimental hair animation', () => {
  assert.equal((panel.match(/className="v6-export-primary"/g) || []).length, 1)
  assert.match(panel, /EXPORTAR MP4 · COM ANIMAÇÃO DE CABELO/)
  assert.match(panel, /className="v6-export-without-hair"[\s\S]*start\(false\)/)
  assert.match(panel, /start\(true\)/)
  assert.doesNotMatch(panel, /setTestMode|EDITOR_V6_EXPORT_TEST_MODES|aria-pressed=\{testMode|v6-export-lab-modes|testMode\s*\}/)
  assert.doesNotMatch(css, /\.v6-export-lab-(choice|grid|modes)/)
})
test('standard action uses the same 1080p Turbo CPU H264 hair/face/boca profile, without testMode override', () => {
  assert.match(profile, /width:\s*1920,\s*height:\s*1080,\s*turbo:\s*true,\s*forceTurbo1080:\s*true,\s*encoder:\s*'cpu'/)
  assert.match(profile, /mouthLoop:\s*true,\s*mouthLoopCycleFrames:\s*30/)
  assert.match(profile, /hairPoseReactionOnly:\s*true,\s*hairPosteriorOnly:\s*true/)
  const argument = controller.match(/options:\s*\{\s*\.\.\.options,\s*\.\.\.DEFAULT_EXPORT_SETTINGS,\s*\.\.\.\(animateHair \? \{\} : \{ hairPoseReactionOnly: false, hairPosteriorOnly: false \}\),\s*mouthLoopCycleFrames:\s*options\.mouthLoopCycleFrames\s*\}/)
  assert.ok(argument, 'The UI must send the default preset without experimental testMode.')
  assert.match(controller, /if \(animateHair && !selectedHairPreset\)/)
  assert.match(controller, /animateHair && selectedHairPreset \? hairMotionPosteriorOnlyPreset\(selectedHairPreset\) : null/)
})
