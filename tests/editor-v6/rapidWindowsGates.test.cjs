'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const { parseOptions, assertWindows, planSteps, helpText } = require('../../scripts/editor-v6/rapid-gates-windows.cjs')

test('quick gate defaults to hair and has no expensive steps', () => {
  const options = parseOptions([])
  assert.deepEqual(options, { gate: 'unit', scope: 'hair', withMp4: false })
  const steps = planSteps(options)
  assert.equal(steps.length, 2)
  assert.ok(steps.every(s => !/build|mp4|electron|typecheck/.test(s.id)))
  assert.ok(steps[1].args.includes('tests/editor-v6/hairBakeBatch.test.ts'))
})
test('render gate selects frame plan and compositor tests without Electron', () => {
  const steps = planSteps(parseOptions(['--gate=unit', '--scope=render']))
  assert.ok(steps.some(s => s.id === 'native-compositor-unit'))
  assert.ok(steps.some(s => s.args.includes('tests/editor-v6/exportDrawPlan.test.ts')))
  assert.ok(!steps.some(s => s.id.includes('offscreen')))
})
test('offscreen gate calls hidden-window fixtures, not MP4 or build', () => {
  const steps = planSteps(parseOptions(['--gate=offscreen', '--scope=all']))
  assert.ok(steps.some(s => s.id === 'electron-hair-motion-offscreen'))
  assert.ok(steps.some(s => s.id === 'electron-scene-offscreen'))
  assert.ok(!steps.some(s => s.id === 'build' || s.id.includes('mp4')))
})
test('integration requires explicit MP4 approval and never includes full project benchmark', () => {
  const plain = planSteps(parseOptions(['--gate=integration', '--scope=character']))
  assert.ok(plain.some(s => s.id === 'typecheck'))
  assert.ok(plain.some(s => s.id === 'build'))
  assert.ok(!plain.some(s => s.id.startsWith('mp4')))
  const full = planSteps(parseOptions(['--gate=integration', '--scope=hair', '--with-mp4']))
  assert.ok(full.some(s => s.id === 'mp4-hair-offscreen'))
  assert.ok(full.some(s => s.id === 'mp4-overlay-offscreen'))
  assert.ok(!full.some(s => s.args.some(arg => arg.includes('benchmark-project-export'))))
})
test('rejects unknown scopes, duplicate flags and accidental heavy MP4', () => {
  assert.throws(() => parseOptions(['--scope=linux']))
  assert.throws(() => parseOptions(['--scope=hair', '--scope=render']))
  assert.throws(() => parseOptions(['--with-mp4']))
  assert.throws(() => parseOptions(['--gate=offscreen', '--with-mp4']))
  assert.throws(() => parseOptions(['--unknown']))
  assert.equal(parseOptions(['--help']).help, true)
  assert.match(helpText(), /Windows x64/)
})
test('disallows tests on Linux or macOS and on Windows ARM', () => {
  assert.doesNotThrow(() => assertWindows('win32', 'x64'))
  assert.throws(() => assertWindows('linux', 'x64'))
  assert.throws(() => assertWindows('darwin', 'arm64'))
  assert.throws(() => assertWindows('win32', 'arm64'))
})
