import type { PoseArtwork } from '../../../../shared/videoCharacterInterpolation'
import type { PreparedGachaLayerFrame } from '../../characters/characterRenderer'
import {
  gachaArticulatedCommands, gachaFaceTransport, type GachaAffine, type GachaArticulatedAssets,
  type GachaDrawCommand,
} from './pixiGachaArticulatedAssets'

type Pixi = typeof import('pixi.js')
type PixiApp = import('pixi.js').Application
type PixiSprite = import('pixi.js').Sprite
type PixiContainer = import('pixi.js').Container
type GachaTexture = import('pixi.js').Texture

function modelHead(artwork: PoseArtwork) {
  return artwork.parts.find(part => /cabe[çc]a|head/i.test(part.name))
}
/**
 * Full bone-linked Gacha rendering surface. No full-character Canvas
 * preparation on the hot path: Pixi repositions persistent body/garment/hair
 * sprites. Face Canvas is generated by the EXACT legacy face painter on a
 * reference pose and transported with the articulated head.
 *
 * This remains opt-in until pixel oracle verifies difficult cases such as
 * pupil masks, animated blush and nonuniform body scaling.
 */
export class PixiGachaArticulatedSurface {
  readonly canvas: HTMLCanvasElement
  private readonly lower: PixiContainer
  private readonly front: PixiContainer
  private readonly root: PixiContainer
  private readonly face: PixiSprite
  private readonly sprites = new Map<string, PixiSprite>()
  private readonly textures = new Map<string, GachaTexture>()
  private lowerOrder = ''
  private frontOrder = ''
  private disposed = false
  private lost = false
  private frameCount = 0
  private readonly onLost = (event: Event) => { event.preventDefault(); this.lost = true }
  private constructor(
    private readonly pixi: Pixi, private readonly app: PixiApp,
    private readonly assets: GachaArticulatedAssets,
    private readonly referenceArtwork: PoseArtwork,
    faceCanvas: HTMLCanvasElement,
  ) {
    this.canvas = app.canvas as HTMLCanvasElement
    this.root = new pixi.Container()
    this.lower = new pixi.Container()
    this.front = new pixi.Container()
    this.face = new pixi.Sprite(pixi.Texture.from(faceCanvas))
    this.face.anchor.set(0)
    this.face.width = faceCanvas.width
    this.face.height = faceCanvas.height
    this.root.addChild(this.lower, this.face, this.front)
    app.stage.addChild(this.root)
    this.canvas.addEventListener('webglcontextlost', this.onLost)
  }
  static async create(assets: GachaArticulatedAssets, referenceArtwork: PoseArtwork,
    face: HTMLCanvasElement, width: number, height: number): Promise<PixiGachaArticulatedSurface> {
    if (!Number.isSafeInteger(width) || !Number.isSafeInteger(height) ||
        width < 1 || height < 1 || width > 8192 || height > 8192)
      throw new Error('Dimensões Pixi Gacha fora dos limites.')
    const pixi = await import('pixi.js')
    const app = new pixi.Application()
    try {
      await app.init({
        width, height, preference:'webgl',preferWebGLVersion:2,
        autoStart:false,sharedTicker:false,backgroundAlpha:0,resolution:1,
        antialias:false,preserveDrawingBuffer:true,
      })
      const instance = new PixiGachaArticulatedSurface(pixi,app,assets,referenceArtwork,face)
      // Prepare once: no intermediate PNGs, no extra outfit/hairstyle
      // conversions, and no asynchronous image decode in the RAF path.
      const urls = new Set<string>([
        ...[...assets.body.values()].map(asset=>asset.url),
        ...assets.hairBack.map(asset=>asset.url),
        ...assets.hairFront.map(asset=>asset.url),
        ...assets.garments.map(asset=>asset.url),
      ])
      await Promise.all([...urls].map(async url => {
        const texture = await pixi.Assets.load<GachaTexture>(url)
        if (instance.disposed) return
        instance.textures.set(url, texture)
      }))
      return instance
    } catch (error) {
      if (app.renderer) app.destroy(true,{children:true})
      throw error
    }
  }
  private setMatrix(sprite: PixiSprite, matrix: GachaAffine) {
    sprite.setFromMatrix(new this.pixi.Matrix(...matrix))
  }
  private put(commands: readonly GachaDrawCommand[], container: PixiContainer,
    prefix: string): void {
    const current = new Set(commands.map(cmd => prefix + cmd.id))
    const ordered: PixiSprite[] = []
    for (const cmd of commands) {
      const id = prefix + cmd.id
      const texture = this.textures.get(cmd.url)
      if (!texture) throw new Error('Textura Gacha não preparada para o GPU: '+cmd.id)
      let sprite = this.sprites.get(id)
      if (!sprite) {
        sprite = new this.pixi.Sprite(texture)
        sprite.anchor.set(0)
        this.sprites.set(id,sprite)
      } else if (sprite.texture !== texture) sprite.texture=texture
      // The source dimensions are immutable. Applying the affine after
      // assigning them preserves anisotropic scaling and garment shear.
      sprite.width = cmd.width
      sprite.height = cmd.height
      this.setMatrix(sprite, cmd.matrix)
      sprite.alpha = cmd.alpha
      sprite.visible = true
      ordered.push(sprite)
    }
    for (const [id,sprite] of this.sprites) if (id.startsWith(prefix) && !current.has(id)) sprite.visible=false
    const signature = commands.map(x=>x.id).join('\u001e')
    const changed = prefix==='B' ? signature!==this.lowerOrder : signature!==this.frontOrder
    if (changed) {
      container.removeChildren()
      for (const sprite of ordered) container.addChild(sprite)
      if (prefix==='B') this.lowerOrder=signature
      else this.frontOrder=signature
    }
  }
  /** A single mutable facial layer is uploaded; all outfit/hair images stay in VRAM. */
  render(artwork: PoseArtwork, faceLayer: PreparedGachaLayerFrame): HTMLCanvasElement {
    if (this.disposed) throw new Error('Superfície articulada descartada.')
    if (this.lost) throw new Error('Contexto GPU articulado perdido.')
    if (faceLayer.outputWidth!==this.canvas.width || faceLayer.outputHeight!==this.canvas.height)
      throw new Error('A dimensão do frame mudou durante a animação.')
    const scene = gachaArticulatedCommands(this.assets,artwork)
    this.put(scene.behind,this.lower,'B')
    this.put(scene.front,this.front,'F')
    const baseHead=modelHead(this.referenceArtwork)
    const targetHead=modelHead(artwork)
    if (!baseHead || !targetHead) throw new Error('Cabeça Gacha não disponível para animar o rosto.')
    this.setMatrix(this.face,gachaFaceTransport(baseHead,targetHead))
    if (this.frameCount > 0) this.face.texture.source.update()
    this.root.position.set(
      faceLayer.outputWidth/2-faceLayer.width*this.assets.shapeX/2,
      faceLayer.outputHeight/2-faceLayer.height*this.assets.shapeY/2)
    this.root.scale.set(this.assets.shapeX,this.assets.shapeY)
    this.app.renderer.render(this.app.stage)
    this.frameCount++
    return this.canvas
  }
  /** Readback for sparse visual oracle only (not every video frame). */
  pixels(): Uint8Array | Uint8ClampedArray {
    if (this.lost || this.disposed) throw new Error('Contexto GPU não disponível.')
    return this.app.renderer.extract.pixels(this.app.stage).pixels
  }
  stats() { return {frames:this.frameCount,sprites:this.sprites.size,images:this.textures.size,contextLost:this.lost} }
  dispose(): void {
    if (this.disposed) return
    this.disposed=true
    this.canvas.removeEventListener('webglcontextlost',this.onLost)
    this.app.stage.removeChild(this.root)
    this.root.destroy({children:true})
    this.app.destroy(true,{children:true})
    // Assets manager caches are process-global; never destroy shared sources.
    this.sprites.clear();this.textures.clear()
  }
}
